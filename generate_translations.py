import xml.etree.ElementTree as ET

for lang, strings in locales.items():
    resources = ET.Element("resources")
    for key, val in strings.items():
        string_elem = ET.SubElement(resources, "string", name=key)
        string_elem.text = val
    
    # format xml properly
    ET.indent(resources, space="    ", level=0)
    xml_str = ET.tostring(resources, encoding="unicode", xml_declaration=True)
    
    res_dir = 'app/src/main/res/values'
    if lang != 'en':
        res_dir = f'app/src/main/res/values-{lang}'
    
    os.makedirs(res_dir, exist_ok=True)
    
    with open(f'{res_dir}/strings.xml', 'w', encoding='utf-8') as f:
        f.write(xml_str)
